export const getMapTileUrl = (row: number, col: number): string | undefined => {
  const key = `${pad(row)},${pad(col)}`;
  if (!MAP_TILE_INDEX.has(key)) return undefined;
  return `wydmap://tiles/m${pad(col)}${pad(row)}.png`;
};

export const hasTile = (row: number, col: number): boolean =>
  MAP_TILE_INDEX.has(`${pad(row)},${pad(col)}`);
